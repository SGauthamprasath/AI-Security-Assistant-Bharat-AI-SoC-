#!/usr/bin/env python3
"""Analyse the usability study.

    python3 study/analyze_study.py --report           # REAL data only: reads study/data/*.csv -> results/STUDY_RESULTS.md (+ figure)
    python3 study/analyze_study.py --selftest         # bot data (synthetic=1) from study/_selftest/ -> checks the maths, writes nothing to results/

Measures
  SUS  System Usability Scale (Brooke 1996): odd items (score-1), even items (5-score), sum x 2.5  -> 0-100 (68 = industry average).
  Per participant and condition (A = raw technical evidence, B = plain-language explanation), mean of: action_correct, reason_correct (comprehension),
  confidence, trust, time. Condition effect = B - A, paired within participant:
     paired t-test, Wilcoxon signed-rank, Cohen's dz, and a 10,000-resample bootstrap 95 % CI of the mean difference.
Safety rails: --report refuses any file containing synthetic=1 rows, and refuses n < 5 participants unless --allow-small is given (then flagged PILOT).
"""
import argparse
import glob
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rng = np.random.default_rng(2026)
MEAS = [("action_correct", "chose the right action", True), ("reason_correct", "understood the message type", True), ("confidence", "confidence (1-5)", False),
        ("trust", "trust in the app (1-5)", False), ("time_s", "time per message (s)", False)]


def sus_score(row):
    v = [row[f"sus_{i}"] for i in range(1, 11)]
    if any(pd.isna(x) for x in v):
        return np.nan
    return 2.5 * sum((x - 1) if i % 2 == 0 else (5 - x) for i, x in enumerate(v))   # i=0 is item 1 (odd)


def boot_ci(d, b=10000):
    d = np.asarray(d, float)
    if len(d) < 2:
        return (np.nan, np.nan)
    m = rng.choice(d, size=(b, len(d)), replace=True).mean(axis=1)
    return tuple(np.percentile(m, [2.5, 97.5]))


def analyse(df):
    tr = df[df.row_type == "trial"].copy()
    tr["time_s"] = tr.time_ms / 1000.0
    sv = df[df.row_type == "survey"].copy()
    sv["sus"] = sv.apply(sus_score, axis=1)
    per = tr.groupby(["pid", "condition"])[[m for m, _, _ in MEAS]].mean().reset_index()
    out = {"n_participants": int(tr.pid.nunique()), "sus": sv.sus.dropna().tolist(), "effects": []}
    wide = per.pivot(index="pid", columns="condition")
    for m, label, is_rate in MEAS:
        a, b = wide[(m, "A_raw")], wide[(m, "B_plain")]
        ok = a.notna() & b.notna()
        a, b = a[ok], b[ok]
        d = (b - a).values
        e = {"measure": m, "label": label, "A_mean": float(a.mean()), "B_mean": float(b.mean()), "diff": float(d.mean()), "ci": boot_ci(d), "n": int(len(d))}
        if len(d) >= 3 and np.std(d, ddof=1) > 0:
            e["t_p"] = float(stats.ttest_rel(b, a).pvalue)
            e["dz"] = float(d.mean() / np.std(d, ddof=1))
            try:
                e["wilcoxon_p"] = float(stats.wilcoxon(d).pvalue)
            except ValueError:
                e["wilcoxon_p"] = float("nan")
        out["effects"].append(e)
    # does the system being wrong matter?  (comprehension on trials where detector was right vs wrong)
    out["system_correct_share"] = float(tr.drop_duplicates("scenario_id").system_correct.mean())
    out["per"] = per
    return out


def md(o, pilot):
    s = np.array(o["sus"])
    L = ["# Usability study results (auto-generated by study/analyze_study.py)\n"]
    if pilot:
        L.append("> **PILOT: fewer than 5 participants - descriptive only, no inference.**\n")
    L.append(f"Participants: **{o['n_participants']}** (each saw 10 scenarios, 5 per condition, counterbalanced). Detector correct on {o['system_correct_share']*100:.0f}% of the scenarios shown.\n")
    if len(s):
        ci = boot_ci(s)
        L.append(f"**SUS: mean {s.mean():.1f}** (SD {s.std(ddof=1) if len(s) > 1 else float('nan'):.1f}, 95% bootstrap CI {ci[0]:.1f}-{ci[1]:.1f}); industry average is 68, 'good' >= 73, 'excellent' >= 80.\n")
    L.append("| Measure | A: raw evidence | B: plain-language | B - A (95% CI) | paired t p | Wilcoxon p | dz |\n|---|---|---|---|---|---|---|")
    for e in o["effects"]:
        pct = e["measure"] in ("action_correct", "reason_correct")
        f = (lambda v: f"{v*100:.0f}%") if pct else (lambda v: f"{v:.2f}")
        fd = (lambda v: f"{v*100:+.0f} pts") if pct else (lambda v: f"{v:+.2f}")
        L.append(f"| {e['label']} | {f(e['A_mean'])} | {f(e['B_mean'])} | {fd(e['diff'])} ({fd(e['ci'][0])} to {fd(e['ci'][1])}) | {e.get('t_p', float('nan')):.3f} | {e.get('wilcoxon_p', float('nan')):.3f} | {e.get('dz', float('nan')):.2f} |")
    L.append("\nReading guide: positive B - A on accuracy/confidence/trust means the plain-language explanation helped. Report effect sizes and intervals even if p > 0.05 - with a small n the interval is the honest summary.")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--allow-small", action="store_true")
    a = ap.parse_args()
    if a.selftest:
        files = sorted(glob.glob(os.path.join(ROOT, "study", "_selftest", "ui_bot_*.csv")))
        assert files, "run study/_selftest/ui_smoke_test.py for several pids first"
        df = pd.concat([pd.read_csv(f) for f in files])
        assert (df.synthetic == 0).all() or True
        o = analyse(df)
        # SUS maths check: all-5 on odd items and all-1 on even items must be 100; all-3 must be 50
        r = {f"sus_{i}": (5 if i % 2 else 1) for i in range(1, 11)}
        r2 = {f"sus_{i}": 3 for i in range(1, 11)}
        assert sus_score(pd.Series(r)) == 100 and sus_score(pd.Series(r2)) == 50
        print(f"SELFTEST OK ({o['n_participants']} bot participants; SUS scoring verified; effects computed for {len(o['effects'])} measures). THESE ARE NOT RESULTS.")
        return
    files = sorted(glob.glob(os.path.join(ROOT, "study", "data", "*.csv")))
    if not files:
        print("No real study data yet: put each participant's exported CSV in study/data/ then re-run.")
        sys.exit(2)
    df = pd.concat([pd.read_csv(f) for f in files])
    if (df.synthetic.fillna(0) != 0).any():
        sys.exit("REFUSING: file(s) contain synthetic=1 rows. Remove test data from study/data/.")
    o = analyse(df)
    pilot = o["n_participants"] < 5
    if pilot and not a.allow_small:
        sys.exit(f"Only {o['n_participants']} participants. Re-run with --allow-small to produce a PILOT summary.")
    os.makedirs(os.path.join(ROOT, "results"), exist_ok=True)
    open(os.path.join(ROOT, "results", "STUDY_RESULTS.md"), "w").write(md(o, pilot))
    print(md(o, pilot))


if __name__ == "__main__":
    main()
