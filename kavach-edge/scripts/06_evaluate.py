"""Step 6 - the evaluation script (accuracy + false alarms), end to end.

    python3 scripts/06_evaluate.py            # writes results/metrics.json, results/EVALUATION.md, results/figs/*.png

Evaluation sets (read this before quoting any number):
  SMS   A  held-out TEST split of the public corpora        (in-distribution; real smishing reports + UCI + synthetic legit)
        B  composite TEST messages (text + URL from the TEST host split)     (in-distribution, constructed)
        C  KavachBench-IN DEV   (hand-written, n=164)  - used to fit fusion  => optimistic, shown for transparency
        D  KavachBench-IN TEST  (hand-written, n=98)   - LOCKED, never used for any fitting => the honest OOD number
  URL   E  TEST host split (pathful URLs built from it);  F dev bench;  G locked test bench;  H OpenDNS top domains (benign-only, independent source)
  NET   I  NSL-KDD KDDTest+ (official split; contains unseen attack types)
        J  synthetic pcap functional tests (NOT an accuracy benchmark)
Every rate carries a 95 % Wilson interval.
"""
