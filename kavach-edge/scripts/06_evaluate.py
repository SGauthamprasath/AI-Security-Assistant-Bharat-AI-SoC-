def wilson(k, n, z=1.96):
    if n == 0:
        return (float("nan"), float("nan"))
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def binmetrics(y, flag, score=None):
    y, flag = np.asarray(y), np.asarray(flag).astype(int)
    tp, fp = int(((flag == 1) & (y == 1)).sum()), int(((flag == 1) & (y == 0)).sum())
    fn, tn = int(((flag == 0) & (y == 1)).sum()), int(((flag == 0) & (y == 0)).sum())
    P, N = tp + fn, fp + tn
    out = {"n": int(len(y)), "n_pos": P, "n_neg": N, "tp": tp, "fp": fp, "fn": fn, "tn": tn,
           "accuracy": (tp + tn) / max(len(y), 1), "recall": tp / max(P, 1), "recall_ci": wilson(tp, P),
           "fpr": fp / max(N, 1), "fpr_ci": wilson(fp, N), "precision": tp / max(tp + fp, 1)}
    out["f1"] = 2 * out["precision"] * out["recall"] / max(out["precision"] + out["recall"], 1e-9)
    pi = 0.01  # precision if only 1 % of traffic were scams (deployment-like prior)
    out["precision_at_1pct_prevalence"] = out["recall"] * pi / max(out["recall"] * pi + out["fpr"] * (1 - pi), 1e-12)
    if score is not None and 0 < P < len(y):
        out["auc"] = float(roc_auc_score(y, score))
        out["ap"] = float(average_precision_score(y, score))
    return out


def fmt(m, keys=("accuracy", "recall", "fpr", "precision", "auc")):
    s = []
    for k in keys:
        if k in m:
            if k in ("recall", "fpr"):
                lo, hi = m[k + "_ci"]
                s.append(f"{k}={m[k]*100:.1f}% [{lo*100:.1f}-{hi*100:.1f}]")
            elif k == "auc":
                s.append(f"AUC={m[k]:.3f}")
            else:
                s.append(f"{k}={m[k]*100:.1f}%")
    return "  ".join(s)


def main():
    det = Detector()
    fz = det.fusion
    th = fz.th
    M = {}
    md = ["# Kavach-Edge evaluation (auto-generated by scripts/06_evaluate.py)\n",
          "All rates are shown with 95 % Wilson confidence intervals. 'Flag' = SUSPICIOUS or DANGEROUS; 'block' = DANGEROUS.\n"]

    # ------------------------------------------------------------------ SMS: score helper
    def score_msgs(items, use_fusion=True):
        out = []
        for txt, sender in items:
            ev = det.analyze_message(txt, sender, with_prompt=False)
            out.append((ev["verdict"]["risk_score"], ev["verdict"]["label"], ev))
        return out

    sms_all = pd.read_csv(os.path.join(ROOT, "data", "processed", "sms_all.csv"))
    te = sms_all[sms_all.split == "test"]
    # ---- A: public-corpora test split
    t0 = time.time()
    resA = score_msgs([(t, None) for t in te.text])
    pA = np.array([r[0] for r in resA]); yA = te.label.values
    flagA = pA >= th["message"]["suspicious"]; blockA = pA >= th["message"]["dangerous"]
    M["sms_A_public_test"] = {"flag": binmetrics(yA, flagA, pA), "block": binmetrics(yA, blockA)}
    M["sms_A_by_source"] = {}
    for src in te.source.unique():
        mk = (te.source == src).values
        M["sms_A_by_source"][src] = {"n": int(mk.sum()), "label": int(te[mk].label.iloc[0]), "flag_rate": float(flagA[mk].mean()), "block_rate": float(blockA[mk].mean())}
    print(f"[A] public test n={len(yA)}  ({time.time()-t0:.0f}s)  flag: {fmt(M['sms_A_public_test']['flag'])}")

    # ---- C/D: hand-written benchmarks
    def run_bench(path):
        rows = [json.loads(l) for l in open(path)]
        res = score_msgs([(r["text"], r["sender"]) for r in rows])
        p = np.array([r[0] for r in res]); y = np.array([r["label"] for r in rows])
        return rows, res, p, y

    bench = {}
    for name, path in (("C_dev", "kavachbench_in.jsonl"), ("D_locked_test", "kavachbench_in_test.jsonl")):
        rows, res, p, y = run_bench(os.path.join(ROOT, "data", path))
        bench[name] = (rows, res, p, y)
        M[f"sms_{name}"] = {"flag": binmetrics(y, p >= th["message"]["suspicious"], p), "block": binmetrics(y, p >= th["message"]["dangerous"])}
        print(f"[{name}] n={len(y)} flag: {fmt(M[f'sms_{name}']['flag'])}   block: {fmt(M[f'sms_{name}']['block'], ('recall','fpr'))}")
    # error listing for transparency
    rows, res, p, y = bench["D_locked_test"]
    errs = {"missed_scams": [], "false_alarms": []}
    for r, (pp, lab, ev), yy in zip(rows, res, y):
        if yy == 1 and pp < th["message"]["suspicious"]:
            errs["missed_scams"].append({"text": r["text"], "risk": round(pp, 3), "category": r["category"]})
        if yy == 0 and pp >= th["message"]["suspicious"]:
            errs["false_alarms"].append({"text": r["text"], "risk": round(pp, 3), "category": r["category"], "band": lab})
    json.dump(errs, open(os.path.join(RES, "errors_locked_test.json"), "w"), indent=1, ensure_ascii=False)
    # per-category recall on locked test
    cat = {}
    for r, (pp, lab, ev), yy in zip(rows, res, y):
        if yy == 1:
            c = cat.setdefault(r["category"], [0, 0]); c[1] += 1; c[0] += int(pp >= th["message"]["suspicious"])
    M["sms_D_recall_by_category"] = {k: {"caught": v[0], "n": v[1]} for k, v in cat.items()}

    # ---- ablations (locked test + public test): refit subsets on the same fit data, evaluate on locked test
    fit = np.load(os.path.join(ROOT, "data", "processed", "fusion_fit.npz"))
    Xm, ym, wm = fit["Xm"], fit["ym"], fit["wm"]
    names = fusion.MSG_FEATURES

    def idx_of(prefixes=(), exact=()):
        return [i for i, n in enumerate(names) if n in exact or any(n.startswith(p) for p in prefixes)]
    variants = {
        "text model only": idx_of(exact=("z_sms",)),
        "rules only (SMS + URL rules)": idx_of(prefixes=("S_", "L_", "U_")),
        "text model + SMS rules": idx_of(exact=("z_sms",), prefixes=("S_", "L_")),
        "text model + URL model/rules": idx_of(exact=("z_sms", "z_url", "has_url"), prefixes=("U_",)),
        "FULL fusion": list(range(len(names))),
    }
    # features for locked test, computed once
    def featurise(rows_):
        X = []
        for r in rows_:
            txt, sender = r["text"], r["sender"]
            sc = det.sms.score(txt)
            norm = textnorm.normalize_sms(txt)
            hits = [h["id"] for h in sms_rules.sms_rule_hits(txt, norm, sender)]
            uz, uh = [], []
            for u in textnorm.extract_urls(txt):
                pr = urlkit.parse_url(u)
                if pr["host"]:
                    uz.append(det.url.score_host(pr["host"])["logit"]); uh.append([h[0] for h in urlkit.url_rule_hits(u)])
            X.append(fusion.message_vector(sc["logit"], uz, hits, uh))
        return np.array(X)
    XD = featurise(bench["D_locked_test"][0]); yD = bench["D_locked_test"][3]
    abl = {}
    for vn, ii in variants.items():
        w, b = fusion.fit_constrained_lr(Xm[:, ii], ym, [names[i] for i in ii], wm, lam=30.0)
        zfit = Xm[:, ii] @ w + b
        pf = fusion.sigmoid(zfit)
        negs = ym == 0
        order = np.argsort(pf[negs]); cw = np.cumsum(wm[negs][order]) / wm[negs].sum()
        thr = pf[negs][order][min(np.searchsorted(cw, 1 - 0.03), negs.sum() - 1)] + 1e-9   # same 3 % false-alarm budget on fit data
        pD = fusion.sigmoid(XD[:, ii] @ w + b)
        m = binmetrics(yD, pD >= thr, pD)
        abl[vn] = m
        print(f"   ablation [{vn:32s}] locked-test: {fmt(m, ('recall','fpr','auc'))}")
    M["sms_ablation_locked_test"] = abl

    # ---- B: composite test
    uh = pd.read_csv(os.path.join(ROOT, "data", "processed", "url_hosts.csv"))
    uh_te = uh[uh.split == "test"]
    import importlib.util
    spec = importlib.util.spec_from_file_location("fit05", os.path.join(ROOT, "scripts", "05_fit_fusion.py"))
    f05 = importlib.util.module_from_spec(spec); spec.loader.exec_module(f05)
    phish_full = f05.load_phish_urls()
    ph = uh_te[uh_te.label == 1].host.tolist()
    bt = uh_te[(uh_te.label == 0) & (uh_te["rank"] <= 50000)].host.tolist()
    ba = uh_te[uh_te.label == 0].host.tolist()
    comp = []
    for t, lab in zip(te.text, te.label):
        r = rng.random()
        if lab == 1:
            urls = [] if r < 0.4 else ([phish_full.get(h, "http://" + h + "/") for h in [rng.choice(ph)]] if r < 0.88 else [f05.short_url()])
        else:
            urls = [] if r < 0.55 else ([f05.benign_url(rng.choice(bt if rng.random() < 0.7 else ba))] if r < 0.96 else [f05.short_url()])
        txt = t
        for u in urls:
            txt = txt.replace("<URL>", u, 1) if "<URL>" in txt else txt + " " + u
        comp.append(txt)
    resB = score_msgs([(t, None) for t in comp]); pB = np.array([r[0] for r in resB])
    M["sms_B_composite_test"] = {"flag": binmetrics(yA, pB >= th["message"]["suspicious"], pB), "block": binmetrics(yA, pB >= th["message"]["dangerous"])}
    print(f"[B] composite test n={len(yA)} flag: {fmt(M['sms_B_composite_test']['flag'])}")

    # ------------------------------------------------------------------ URL
    def url_eval(urls, labels):
        res = [det.analyze_url(u, with_prompt=False) for u in urls]
        p = np.array([r["verdict"]["risk_score"] for r in res])
        mz = np.array([r["model_outputs"]["urls"][0]["p_phish"] for r in res])
        return p, mz, res
    n_each = 5000
    urls_E = [(phish_full.get(h, "http://" + h + "/"), 1) for h in rng.sample(ph, min(n_each, len(ph)))] + [(f05.benign_url(h), 0) for h in rng.sample(ba, n_each)]
    pE, mzE, _ = url_eval([u for u, _ in urls_E], None); yE = np.array([l for _, l in urls_E])
    th_u = th["url"]
    M["url_E_test_hosts"] = {"fused_flag": binmetrics(yE, pE >= th_u["suspicious"], pE), "fused_block": binmetrics(yE, pE >= th_u["dangerous"]),
                             "host_model_only_auc": float(roc_auc_score(yE, mzE))}
    fpr_, tpr_, _ = roc_curve(yE, mzE)
    M["url_E_test_hosts"]["host_model_tpr_at_fpr1pct"] = float(tpr_[np.searchsorted(fpr_, 0.01)])
    print(f"[E] url test: fused flag {fmt(M['url_E_test_hosts']['fused_flag'])} | host-model AUC {M['url_E_test_hosts']['host_model_only_auc']:.3f}")
    for name, path in (("F_dev", "kavachbench_urls.jsonl"), ("G_locked_test", "kavachbench_urls_test.jsonl")):
        rr = [json.loads(l) for l in open(os.path.join(ROOT, "data", path))]
        p, mz, res = url_eval([r["url"] for r in rr], None); y = np.array([r["label"] for r in rr])
        M[f"url_{name}"] = {"fused_flag": binmetrics(y, p >= th_u["suspicious"], p), "fused_block": binmetrics(y, p >= th_u["dangerous"]), "host_model_only_flag": binmetrics(y, mz >= 0.5, mz)}
        print(f"[{name}] n={len(y)} fused flag: {fmt(M[f'url_{name}']['fused_flag'], ('recall','fpr','auc'))} | host-model-only@0.5: {fmt(M[f'url_{name}']['host_model_only_flag'], ('recall','fpr','auc'))}")
        if name == "G_locked_test":
            M["url_G_errors"] = [{"url": r["url"], "label": r["label"], "risk": round(float(pp), 3)} for r, pp in zip(rr, p) if (r["label"] == 1) != (pp >= th_u["suspicious"])]
    odns = [l.strip() for l in open(os.path.join(ROOT, "data", "raw", "opendns_top.txt")) if l.strip() and "." in l][:6000]
    resO = [det.analyze_url("https://" + d + "/", with_prompt=False) for d in odns]
    pO = np.array([r["verdict"]["risk_score"] for r in resO])
    M["url_H_opendns_benign"] = {"n": len(odns), "fpr_flag": float((pO >= th_u["suspicious"]).mean()), "fpr_block": float((pO >= th_u["dangerous"]).mean()),
                                 "fpr_flag_ci": wilson(int((pO >= th_u["suspicious"]).sum()), len(odns))}
    print(f"[H] OpenDNS top domains (benign only) n={len(odns)}: flagged {M['url_H_opendns_benign']['fpr_flag']*100:.2f}%")

    # ------------------------------------------------------------------ NETWORK (KDDTest+)
    nm = det.net
    te_n = pd.read_csv(os.path.join(ROOT, "data", "raw", "KDDTest+.txt"), header=None, names=netkit.ALL_COLS + ["label", "difficulty"])
    te_n["cls"] = te_n.label.map(netkit.ATTACK_CATEGORY)
    Xn = np.vstack([netkit.encode_row(r, nm.meta) for r in te_n[netkit.DEPLOY_COLS].to_dict("records")])
    out = nm.predict(Xn)
    yn = te_n.cls.map(netkit.CLASSES.index).values; yb = (yn != 0).astype(int)
    pn = out["p_attack"]
    tn_ = th["network"]
    M["net_I_kddtest"] = {"flag@0.5": binmetrics(yb, pn >= tn_["suspicious"], pn), "block@0.9": binmetrics(yb, pn >= tn_["dangerous"]),
                          "recall_by_class": {c: float(((pn >= tn_["suspicious"]) & (yn == i)).sum() / max((yn == i).sum(), 1)) for i, c in enumerate(netkit.CLASSES) if i > 0},
                          "n_by_class": {c: int((yn == i).sum()) for i, c in enumerate(netkit.CLASSES)}}
    print(f"[I] KDDTest+ n={len(yb)} flag@{tn_['suspicious']}: {fmt(M['net_I_kddtest']['flag@0.5'], ('accuracy','recall','fpr','precision','auc'))}")
    print("    recall by class:", {k: round(v, 3) for k, v in M["net_I_kddtest"]["recall_by_class"].items()})
    fpr_n, tpr_n, thr_n = roc_curve(yb, pn)
    pd.DataFrame({"threshold": thr_n, "fpr": fpr_n, "tpr": tpr_n}).to_csv(os.path.join(RES, "net_operating_curve.csv"), index=False)
    M["net_ablation_41_vs_28"] = json.load(open(os.path.join(RES, "net_ablation.json")))

    # pcap functional tests
    expect = {"normal_browsing": None, "port_scan": "port scan", "syn_flood": "SYN flood", "ping_flood": "ping flood", "smurf_like": "smurf"}
    pc = {}
    for n, e in expect.items():
        r = det.analyze_pcap(os.path.join(ROOT, "demo", "pcaps", n + ".pcap"), with_prompt=False)
        labels = [a["category_text"] for a in r["alerts"]]
        ok = (len(labels) == 0) if e is None else any(e.lower() in l.lower() for l in labels)
        pc[n] = {"connections": r["summary"]["connections"], "flagged": r["summary"]["flagged"], "alerts": labels, "pass": bool(ok)}
        print(f"[J] pcap {n:18s} conns={r['summary']['connections']:5d} flagged={r['summary']['flagged']:5d} alerts={labels} -> {'PASS' if ok else 'FAIL'}")
    M["net_J_pcap_functional"] = pc

    json.dump(M, open(os.path.join(RES, "metrics.json"), "w"), indent=1, default=float)
    make_report(M, md)
    make_figs(M, yD, XD, Xm, ym, wm, variants, names, yE, pE, mzE, fpr_n, tpr_n, yn, out, nm)


def make_report(M, md):
    L = md
    P = lambda m, keys=("accuracy", "recall", "fpr", "precision", "auc"): fmt(m, keys)
    L.append("## 1. Scam message detection (SMS / chat)\n")
    L.append("| Set | n (scam/legit) | recall (flag) | false-alarm rate (flag) | recall (block) | false-alarm (block) | AUC |\n|---|---|---|---|---|---|---|")
    names = {"sms_A_public_test": "A. public-corpora TEST split (in-distribution)", "sms_B_composite_test": "B. composite TEST (text+URL, in-distribution)",
             "sms_C_dev": "C. KavachBench-IN DEV (tuned on - optimistic)", "sms_D_locked_test": "**D. KavachBench-IN LOCKED TEST (out-of-distribution)**"}
    for k, nme in names.items():
        f, b = M[k]["flag"], M[k]["block"]
        L.append(f"| {nme} | {f['n_pos']}/{f['n_neg']} | {f['recall']*100:.1f}% [{f['recall_ci'][0]*100:.0f}-{f['recall_ci'][1]*100:.0f}] | {f['fpr']*100:.1f}% [{f['fpr_ci'][0]*100:.1f}-{f['fpr_ci'][1]*100:.1f}] | {b['recall']*100:.1f}% | {b['fpr']*100:.1f}% | {f.get('auc', float('nan')):.3f} |")
    L.append("\n**Ablation on the locked test** (each variant re-fitted on the same data, same 3 % false-alarm budget):\n")
    L.append("| Variant | recall | false-alarm | AUC |\n|---|---|---|---|")
    for k, m in M["sms_ablation_locked_test"].items():
        L.append(f"| {k} | {m['recall']*100:.1f}% [{m['recall_ci'][0]*100:.0f}-{m['recall_ci'][1]*100:.0f}] | {m['fpr']*100:.1f}% [{m['fpr_ci'][0]*100:.1f}-{m['fpr_ci'][1]*100:.1f}] | {m.get('auc', float('nan')):.3f} |")
    L.append("\nPer-category recall on the locked test: " + ", ".join(f"{k} {v['caught']}/{v['n']}" for k, v in M["sms_D_recall_by_category"].items()))
    L.append("\n## 2. Phishing URL detection\n")
    e = M["url_E_test_hosts"]
    L.append(f"* Host-only ML model on the held-out TEST host split: AUC **{e['host_model_only_auc']:.3f}**, TPR at 1 % FPR **{e['host_model_tpr_at_fpr1pct']*100:.1f}%** (benign hosts are sampled across the whole Tranco rank range, so many are obscure long-tail domains - a deliberately hard setting).")
    L.append(f"* Full URL analysis (ML + rules, path/query visible) on pathful URLs built from the TEST hosts: {P(e['fused_flag'], ('recall','fpr','auc'))}")
    for k, n_ in (("url_F_dev", "dev bench"), ("url_G_locked_test", "locked test bench")):
        m = M[k]
        L.append(f"* Hand-written URL {n_} (n={m['fused_flag']['n']}): fused {P(m['fused_flag'], ('recall','fpr','auc'))}; host-model alone {P(m['host_model_only_flag'], ('recall','fpr','auc'))}")
    h = M["url_H_opendns_benign"]
    L.append(f"* Independent benign source (OpenDNS top domains, n={h['n']}): false-alarm rate **{h['fpr_flag']*100:.2f}%** (flag), {h['fpr_block']*100:.2f}% (block).")
    L.append("\n## 3. Network intrusion detection (NSL-KDD, official KDDTest+)\n")
    n = M["net_I_kddtest"]["flag@0.5"]
    L.append(f"* 28 deployable features, flag threshold {0.5}: {P(n, ('accuracy','recall','fpr','precision','auc'))}")
    L.append("* Recall by attack family: " + ", ".join(f"{k} {v*100:.0f}% (n={M['net_I_kddtest']['n_by_class'][k]})" for k, v in M["net_I_kddtest"]["recall_by_class"].items()))
    a = M["net_ablation_41_vs_28"]
    L.append(f"* Ablation (argmax, 5-class): all 41 features acc {a['all41']['acc_5class']*100:.1f}% / AUC {a['all41']['auc']:.3f}; deployable 28 features acc {a['deploy28']['acc_5class']*100:.1f}% / AUC {a['deploy28']['auc']:.3f} - dropping payload-inspection features costs little.")
    L.append("* R2L / U2R attacks (password guessing, privilege escalation) are largely invisible to header-only features; KDDTest+ also contains attack variants absent from training. These limits are stated, not hidden.")
    L.append("\n**Synthetic pcap functional tests** (fixtures, *not* an accuracy benchmark):\n")
    L.append("| pcap | connections | flagged | alerts | result |\n|---|---|---|---|---|")
    for k, v in M["net_J_pcap_functional"].items():
        L.append(f"| {k} | {v['connections']} | {v['flagged']} | {', '.join(v['alerts']) or '-'} | {'PASS' if v['pass'] else 'FAIL'} |")
    open(os.path.join(RES, "EVALUATION.md"), "w").write("\n".join(L) + "\n")


def make_figs(M, yD, XD, Xm, ym, wm, variants, names, yE, pE, mzE, fpr_n, tpr_n, yn, out, nm):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 10, "axes.edgecolor": GRID, "axes.labelcolor": MUTED, "xtick.color": MUTED, "ytick.color": MUTED, "axes.spines.top": False, "axes.spines.right": False})

    def roc_ax(ax, curves, title):
        for lab, (y, s), col in curves:
            f, t, _ = roc_curve(y, s)
            ax.plot(f, t, color=col, lw=2, label=f"{lab} (AUC {roc_auc_score(y, s):.3f})")
