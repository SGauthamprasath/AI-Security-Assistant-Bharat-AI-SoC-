#!/usr/bin/env python3
"""Generate the 'Hardware & Performance' report section from measured files only.

    python3 bench/make_report.py     ->  report/sections/05_hardware_performance.md  +  results/figs/latency_stages.png

Inputs : results/bench/bench_*.json (from run_bench.py), results/bench/adb_*/summary.json (from parse_adb.py)
Rule   : if a number was not measured, the table cell says PENDING and the exact command to run is printed. Nothing is filled
         from memory, from a spec sheet or from x86 runs. x86 runs are shown in a separate, clearly labelled table.
"""
import glob
import json
import os
import statistics

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "report", "sections", "05_hardware_performance.md")
os.makedirs(os.path.dirname(OUT), exist_ok=True)
PEND = "**PENDING**"
TARGET = {"p95_ms": 50, "cold_s": 1.0, "rss_mb": 150, "model_mb": 10}


def load():
    runs = {}
    for f in sorted(glob.glob(os.path.join(ROOT, "results", "bench", "bench_*.json"))):
        j = json.load(open(f))
        runs.setdefault(j["label"], []).append(j)
    return runs


def med(vals):
    vals = [v for v in vals if v is not None]
    return statistics.median(vals) if vals else None


def g(j, *path):
    for p in path:
        if not isinstance(j, dict) or p not in j:
            return None
        j = j[p]
    return j


def f(v, nd=2, suffix=""):
    return PEND if v is None else f"{v:.{nd}f}{suffix}"


def row(label, runs):
    m = runs[0]["machine"]
    return {
        "label": label, "n_runs": len(runs), "arm": m["is_arm"], "cpu": m.get("cpu_model") or m["machine"], "cpus": m.get("logical_cpus"),
        "note": runs[0].get("device_note", ""),
        "cold_load": med([g(r, "cold_start", "load_ms", "p50") for r in runs]), "cold_first": med([g(r, "cold_start", "first_verdict_ms", "p50") for r in runs]),
        "p50": med([g(r, "message_latency_ms", "total", "p50") for r in runs]), "p95": med([g(r, "message_latency_ms", "total", "p95") for r in runs]),
        "p99": med([g(r, "message_latency_ms", "total", "p99") for r in runs]), "url_p50": med([g(r, "url_latency_ms", "p50") for r in runs]),
        "thr": med([r.get("throughput_msgs_per_s") for r in runs]), "rss": med([g(r, "memory_after_message_workload", "rss_mb") for r in runs]),
        "pss": med([g(r, "memory_after_message_workload", "pss_mb") for r in runs]),
        "rss_pcap": med([g(r, "memory_after_workload", "rss_mb") for r in runs]), "models_mb": med([sum(r["model_files_bytes"].values()) / 1e6 for r in runs]),
        "pcap": g(runs[0], "pcap_analysis"), "stages": g(runs[0], "message_latency_ms", "stages"),
        "advisor": g(runs[0], "advisor"), "sustained": g(runs[0], "sustained"),
    }


def conditions(k, rs):
    """How and under what conditions an Arm device was measured, so no number is read out of context."""
    out = [f"**{k}: conditions and method**\n"]
    for i, r in enumerate(rs, 1):
        out.append(f"* run {i}: {r.get('device_note') or 'no device note'}")
    notes = " ".join(r.get("device_note", "") for r in rs)
    cs = g(rs[0], "cold_start", "source")
    if cs:
        ps = g(rs[0], "cold_start", "python_start_ms", "p50")
        n = g(rs[0], "cold_start", "load_ms", "n")
        out.append(f"* cold start (n={n}): {cs}" + (f"; Python start p50 {ps:.0f} ms comes on top of the cold start shown above." if ps else "."))
    if "airplane=0" in notes:
        out.append("* **Deviation from protocol: airplane mode was OFF** during these runs (the phone was USB-tethering the laptop). "
                   "The app has no INTERNET permission and the detector has no network code, but radio activity can affect heat and CPU load.")
    if "Chaquopy" in notes:
        out.append("* RSS/PSS are for the whole Android app process (Android runtime + embedded Python + detector), not a bare Python "
                   "process; the 150 MB RSS target was set for the latter. PSS is the memory Android charges the app.")
    out.append("")
    return out


def main():
    runs = load()
    rows = {k: row(k, v) for k, v in runs.items()}
    arm = {k: r for k, r in rows.items() if r["arm"]}
    ref = {k: r for k, r in rows.items() if not r["arm"]}
    L = ["# 5. Hardware and performance\n",
         "*Generated by `bench/make_report.py` from `results/bench/*.json`. Protocol: `bench/BENCHMARK_PROTOCOL.md`. "
         "Every cell is a measurement or the word **PENDING**.*\n"]

    L.append("## 5.1 Measured on Arm hardware\n")
    if not arm:
        L.append(f"{PEND} - no Arm run has been recorded yet. Run on the phone / Raspberry Pi:\n\n"
                 "```bash\npython3 bench/run_bench.py --label phone_arm64 --device-note \"<model>, Android <ver>, <RAM>, battery <pct>%\" --iters 2000\n```\n")
    else:
        L.append("| Device | CPU | runs | cold start (load + first verdict) | message p50 / p95 / p99 | URL p50 | throughput | RSS / PSS (detector) | RSS with pcap parser | detector files |\n|---|---|---|---|---|---|---|---|---|---|")
        for k, r in arm.items():
            L.append(f"| {k} | {r['cpu']} ({r['cpus']} cores) | {r['n_runs']} | {f((r['cold_load'] or 0) + (r['cold_first'] or 0), 0, ' ms') if r['cold_load'] else PEND} | "
                     f"{f(r['p50'])} / {f(r['p95'])} / {f(r['p99'])} ms | {f(r['url_p50'])} ms | {f(r['thr'], 0, ' msg/s')} | {f(r['rss'], 0)} / {f(r['pss'], 0)} MB | {f(r['rss_pcap'], 0)} MB | {f(r['models_mb'], 2, ' MB')} |")
        L.append("\nTargets: " + ", ".join(f"{k} {v}" for k, v in TARGET.items()) + ".\n")
        for k, r in arm.items():
            ok = [("p95 < 50 ms", r["p95"] is not None and r["p95"] < TARGET["p95_ms"]),
                  ("cold start < 1 s", r["cold_load"] is not None and (r["cold_load"] + (r["cold_first"] or 0)) < 1000),
                  ("RSS < 150 MB", r["rss"] is not None and r["rss"] < TARGET["rss_mb"]), ("model files < 10 MB", r["models_mb"] is not None and r["models_mb"] < TARGET["model_mb"])]
            L.append(f"* **{k}** targets: " + "; ".join(f"{n}: {'MET' if v else 'MISSED'}" for n, v in ok))
        L.append("")
        for k in arm:
            L += conditions(k, runs[k])

    L.append("## 5.2 Development reference (x86 sandbox) - NOT Arm, shown only to localise bottlenecks\n")
    if ref:
        L.append("| Machine | message p50 / p95 / p99 | URL p50 | throughput | RSS / PSS (detector) | RSS with pcap parser | detector files |\n|---|---|---|---|---|---|---|")
        for k, r in ref.items():
            L.append(f"| {k} (`{r['cpu']}`) | {f(r['p50'], 3)} / {f(r['p95'], 3)} / {f(r['p99'], 3)} ms | {f(r['url_p50'], 3)} ms | {f(r['thr'], 0, ' msg/s')} | {f(r['rss'], 0)} / {f(r['pss'], 0)} MB | {f(r['rss_pcap'], 0)} MB | {f(r['models_mb'], 2, ' MB')} |")
        L.append("\nOptimisation done from this profile: the NumPy tree evaluator walked trees one by one (about 8.4 ms per URL); it now walks all trees per level "
                 "(about 0.5 ms per URL) with bit-level parity (max |diff| 7e-15). Arm cores will be slower than a server core - the Arm table above is the one that counts.\n")

    st = (arm or ref)
    if st:
        k0 = next(iter(st))
        r0 = st[k0]
        if r0["stages"]:
            L.append(f"## 5.3 Where the time goes ({k0}, per message)\n\n| stage | p50 ms | p95 ms | p99 ms |\n|---|---|---|---|")
            for s, v in r0["stages"].items():
                L.append(f"| {s} | {v['p50']:.3f} | {v['p95']:.3f} | {v['p99']:.3f} |")
            L.append("")
        if r0["pcap"]:
            L.append(f"Network monitor ({k0}): " + "; ".join(f"{n}: {v['connections']} connections in {v['ms_p50']} ms ({v['connections_per_s']:.0f}/s)" for n, v in r0["pcap"].items()) + ".\n")

    L.append("## 5.4 On-device LLM advisor (Llama via ExecuTorch)\n")
    adv = [(k, r["advisor"]) for k, r in rows.items() if r["advisor"] and r["advisor"].get("measured")]
    if adv:
        L.append("| Device | runs x samples | time-to-first-token p50 | total p50 | decode tokens/s p50 | prefill tokens/s p50 | output tokens p50 | model load | peak RSS (app) |\n"
                 "|---|---|---|---|---|---|---|---|---|")
        for k, a in adv:
            rs = [r for r in runs[k] if g(r, "advisor", "measured")]

            def m(*p):   # median over runs of each run's value (each run's value is its own p50)
                return med([g(r, "advisor", *p) for r in rs])
            rss = med([g(r, "memory_after_advisor", "rss_mb") for r in rs])
            L.append(f"| {k} | {len(rs)} x {a.get('samples', '?')} | {f(m('ttfb_ms', 'p50'), 0, ' ms')} | {f(m('total_ms', 'p50'), 0, ' ms')} | "
                     f"{f(m('tokens_per_s', 'p50'), 1)} | {f(m('prefill_tokens_per_s', 'p50'), 0)} | {f(m('generated_tokens', 'p50'), 0)} | "
                     f"{f(m('model_load_ms'), 0, ' ms')} | {f(rss, 0, ' MB')} |")
            if a.get("source"):
                shown = med([g(r, "advisor", "shown_from_llama") for r in rs])
                L.append(f"\n*{k}: model `{a.get('model')}`. Measured by: {a['source']}. Each cell is the median over runs of that "
                         f"run's p50. After the output checks, Llama's text was shown for {shown:.0f} of {a.get('samples')} messages per run; "
                         f"the rest fell back to the playbook template.*")
        L.append("")
    else:
        L.append(f"{PEND} - not measured. Wrap the ExecuTorch runner as described in protocol section 4 and run `bench/run_bench.py ... --advisor-cmd ./run_llama.sh`.\n")

    L.append("## 5.5 Sustained load: battery and temperature\n")
    sus = [(k, r["sustained"]) for k, r in arm.items() if r["sustained"] and r["sustained"].get("telemetry")]
    adb = []
    for d in sorted(glob.glob(os.path.join(ROOT, "results", "bench", "adb_*", "summary.json"))):
        adb.append((os.path.basename(os.path.dirname(d))[4:], json.load(open(d))))
    if not sus and not adb:
        L.append(f"{PEND} - no Arm sustained run recorded. Run protocol section 5 (30 min idle baseline + 30 min workload).\n")
    for k, s in sus:
        t = s["telemetry"]
        L.append(f"* **{k}** in-process telemetry ({s['seconds']} s, {s['messages_processed']} verdicts): temperature {f(t.get('temp_start_c'), 1)} -> {f(t.get('temp_end_c'), 1)} C "
                 f"(max {f(t.get('temp_max_c'), 1)}), battery drop {f(t.get('battery_drop_pct'), 1)} %, latency drift first->last minute {f(s.get('latency_drift_pct_first_to_last_minute'), 1)} %.")
    base = next((s for n, s in adb if "idle" in n and s.get("ok")), None)
    for n, s in adb:
        if "idle" in n:
            continue
        if not s.get("ok"):
            L.append(f"* **{n}** adb run INVALID: {s.get('reason')}")
            continue
        extra = ""
        if base and s.get("drain_pct_per_hour") is not None and base.get("drain_pct_per_hour") is not None:
            extra = f"; drain above idle {s['drain_pct_per_hour'] - base['drain_pct_per_hour']:.2f} %/h"
        L.append(f"* **{n}** (adb, {s.get('model', '?')}, {s.get('abi', '?')}): battery {s['battery_start_pct']}% -> {s['battery_end_pct']}% in {s['duration_s']/60:.0f} min "
                 f"(drain {f(s.get('drain_pct_per_hour'), 2, ' %/h')}{extra}), temperature {s['temp_start_c']} -> max {s['temp_max_c']} C, thermal status max {s.get('thermal_status_max')}.")
    L.append("")

    L.append("## 5.6 Memory and size summary\n")
    any_r = next(iter(rows.values()), None)
    if any_r:
        files = runs[next(iter(runs))][0]["model_files_bytes"]
        L.append("| file | KB |\n|---|---|")
        for n, b in files.items():
            L.append(f"| {n} | {b/1024:.0f} |")
        L.append(f"| **total** | **{sum(files.values())/1024:.0f}** |\n")
    L.append("Reproduce: `bash bench/BENCHMARK_PROTOCOL.md` section 3 on the device, then `python3 bench/make_report.py`.\n")
    open(OUT, "w").write("\n".join(L))

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        k0 = next(iter(arm or ref), None)
        if k0 and rows[k0]["stages"]:
            stages = rows[k0]["stages"]
            names = [s for s in stages]
            vals = [stages[s]["p50"] for s in names]
            fig, ax = plt.subplots(figsize=(7.5, 3.4))
            ax.barh(names, vals, color="#2a78d6")
            ax.invert_yaxis()
            for i, v in enumerate(vals):
                ax.text(v, i, f" {v:.3f} ms", va="center", fontsize=8.5, color="#52514e")
            ax.set_xlabel("median ms per message" + ("" if k0 in arm else "  (x86 reference, not Arm)"))
            for s_ in ("top", "right"):
                ax.spines[s_].set_visible(False)
            ax.set_title(f"Where a verdict's time goes - {k0}", loc="left", fontsize=11)
            fig.tight_layout()
            fig.savefig(os.path.join(ROOT, "results", "figs", "latency_stages.png"), dpi=170)
    except Exception as e:  # charts are optional
        print("chart skipped:", e)
    print("wrote", OUT, "| arm runs:", list(arm) or "none yet", "| reference runs:", list(ref))


if __name__ == "__main__":
    main()
